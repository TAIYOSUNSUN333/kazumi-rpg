const riddles = Object.fromEntries(Object.entries(riddleRows).map(([tier, rows]) => [tier, rows.map((row, index) => {
  const [prompt, answer, ...rest] = row.split('|');
  return {id: tier + '-text-' + index, prompt, answer, choices: [answer, ...rest.slice(0, 3)], hint: rest[3]};
})]));

function addNumberRiddle(tier, key, prompt, answer, alternatives, hint) {
  riddles[tier].push({id: tier + '-' + key, prompt, answer: String(answer), choices: [answer, ...alternatives].map(String), hint});
}

for (let n = 2; n <= 26; n++) {
  const fruit = ['りんご', 'みかん', '梨', '桃'][n % 4];
  addNumberRiddle('easy', 'share-' + n,
    `同じ数ずつ入った袋が2つ。片方の袋には${n}個の${fruit}が入っている。合わせて何個？`,
    n * 2, [n, n * 2 - 1, n * 2 + 2], '同じ数をもう一度足します。');
  addNumberRiddle('easy', 'pairs-' + n,
    `片方ずつ数えると手袋が${n * 2}枚。2枚で一組なら、何組にできる？`,
    n, [n - 1, n + 1, n * 2], '左右を合わせて一組と数えます。');
}

